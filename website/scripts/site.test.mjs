import test from "node:test";
import assert from "node:assert/strict";
import { readFile, readdir, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { copy, sourceRef } from "../content.mjs";

const dist = fileURLToPath(new URL("../dist/", import.meta.url));
const read = (path) => readFile(join(dist, path), "utf8");
const files = async (root) =>
  (
    await Promise.all(
      (await readdir(root, { withFileTypes: true })).map(async (item) =>
        item.isDirectory()
          ? files(join(root, item.name))
          : join(root, item.name),
      ),
    )
  ).flat();

test("English and Spanish contain the full product content and valid destinations", async () => {
  assert.deepEqual(Object.keys(copy.en).sort(), Object.keys(copy.es).sort());
  for (const language of ["en", "es"]) {
    const html = await read(`${language}.html`);
    assert.match(html, new RegExp(`<html lang="${language}">`));
    assert.equal((html.match(/<h1>/g) || []).length, 1);
    for (const id of [
      "profiles",
      "workflow",
      "start",
      "examples",
      "reports",
      "docs",
    ])
      assert.ok(html.includes(`id="${id}"`));
    assert.equal((html.match(/<details>/g) || []).length, 6);
    assert.equal((html.match(/data-copy=/g) || []).length, 5);
    assert.match(html, /mailto:felipe\.castillo@lynvera\.ai/);
    assert.match(html, /Dr\. Felipe Castillo Rendón/);
    assert.match(html, /Apache License 2\.0/);
    assert.match(html, /local-knowledge: PASS\. Records: 2\./);
    assert.match(html, /duplicate-ids: FAIL\. Records: 2\./);
    assert.ok(html.includes(sourceRef));
    assert.doesNotMatch(
      html,
      /[\u2190-\u21ff\u2022\u00b7\u{1f300}-\u{1faff}]|&lt;&lt;|&gt;&gt;/u,
    );
    assert.doesNotMatch(
      html,
      /placeholder|lorem ipsum|co-authored-by|generated by|pip install lynvera-aidataready/i,
    );
    const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((x) => x[1]);
    assert.equal(ids.length, new Set(ids).size);
    for (const [, href] of html.matchAll(/href="([^"]+)"/g)) {
      if (href.startsWith("#")) assert.ok(ids.includes(href.slice(1)), href);
      else if (href.startsWith("/") && !["/en", "/es"].includes(href))
        assert.ok(await stat(join(dist, href.slice(1))), href);
      else
        assert.ok(
          href.startsWith("https://") ||
            href.startsWith("mailto:") ||
            ["/en", "/es"].includes(href),
          href,
        );
    }
  }
});

test("metadata identifies the production domain and both languages", async () => {
  for (const language of ["en", "es"]) {
    const html = await read(`${language}.html`);
    assert.ok(
      html.includes(
        `rel="canonical" href="https://aidataready.lynvera.ai/${language}"`,
      ),
    );
    for (const alternate of ["en", "es", "x-default"])
      assert.ok(html.includes(`hreflang="${alternate}"`));
    assert.match(html, /summary_large_image/);
    assert.match(
      html,
      /https:\/\/aidataready\.lynvera\.ai\/assets\/social.png/,
    );
    const graph = JSON.parse(
      html.match(/<script type="application\/ld\+json">(.*?)<\/script>/s)[1],
    );
    assert.equal(graph.version, "0.1.0");
    assert.equal(graph.author.name, "Dr. Felipe Castillo Rendón");
  }
  assert.match(
    await read("sitemap.xml"),
    /https:\/\/aidataready\.lynvera\.ai\/en/,
  );
  assert.match(
    await read("sitemap.xml"),
    /https:\/\/aidataready\.lynvera\.ai\/es/,
  );
  assert.match(
    await read("robots.txt"),
    /Sitemap: https:\/\/aidataready\.lynvera\.ai\/sitemap.xml/,
  );
  assert.match(await read("404.html"), /content="noindex"/);
  assert.equal(await read("_redirects"), "/ /en 302\n");
});

test("the site stays static, local and within Pages Free asset limits", async () => {
  const list = await files(dist);
  assert.ok(list.length < 20000);
  for (const path of list) {
    assert.ok((await stat(path)).size < 25 * 1024 * 1024);
    assert.doesNotMatch(path, /node_modules|_worker|functions\//);
  }
  const headers = await read("_headers");
  assert.match(headers, /script-src 'self'/);
  assert.doesNotMatch(headers, /unsafe-inline|unsafe-eval/);
  assert.match(headers, /connect-src 'none'/);
  assert.match(headers, /pages\.dev\/\*\n  X-Robots-Tag: noindex/);
  const html = await read("en.html");
  assert.doesNotMatch(html, /<(?:script|img)[^>]+src="https?:/);
  assert.match(
    await read("assets/site.css"),
    /prefers-reduced-motion:\s*reduce/,
  );
  assert.match(await read("assets/site.css"), /:focus-visible/);
  assert.ok((await stat(join(dist, "assets/social.png"))).size > 1000);
});

test("synthetic report downloads preserve real statuses and violation counts", async () => {
  const rag = JSON.parse(await read("examples/rag.json"));
  const fail = JSON.parse(await read("examples/duplicates.json"));
  assert.equal(rag.status, "PASS");
  assert.equal(fail.status, "FAIL");
  assert.equal(
    fail.findings.find((f) => f.code === "structure.unique").violations,
    1,
  );
  assert.equal(rag.rows_examined, 2);
  const verification = JSON.parse(await read("examples/verification.json"));
  assert.equal(verification.synthetic, true);
  assert.equal(verification.sourceCommit, sourceRef);
  for (const format of ["json", "html", "xml"])
    assert.ok(
      (await stat(join(dist, `examples/rag-report.${format}`))).size > 100,
    );
});
